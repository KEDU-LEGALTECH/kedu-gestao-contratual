import { readdirSync, readFileSync } from "node:fs";
import type postgres from "postgres";

/** Migrations up to 019 built the SQLite schema the PostgreSQL import was converted from
 * (scripts/postgres-rehearsal.ts). From 020 on they must work on both databases and be idempotent
 * (IF NOT EXISTS): SQLite runs them at every start, PostgreSQL records them in schema_migrations. */
export const firstPortable = 20;
export const portableMigrations = () =>
  readdirSync("migrations")
    .filter((name) => /^\d{3}\.sql$/.test(name) && Number(name.slice(0, 3)) >= firstPortable)
    .sort()
    .map((name) => ({ name, sql: readFileSync("migrations/" + name, "utf8") }));

/** Same column types as the importer, plus the _rowid column that stands in for SQLite's rowid. */
export function postgresDdl(sqlite: string) {
  const source = sqlite.replace(/--[^\n]*/g, "");
  const tables = [...source.matchAll(/\bCREATE\s+TABLE\s+IF\s+NOT\s+EXISTS\s+(\w+)/gi)].map((m) => m[1]);
  const ddl = source.replace(/'(?:[^']|'')*'|"(?:[^"]|"")*"|\b(?:BLOB|INTEGER|REAL)\b|(?<=\w\s+)TEXT\b/gi,
    (token) => ({ BLOB: "BYTEA", INTEGER: "BIGINT", REAL: "DOUBLE PRECISION", TEXT: 'TEXT COLLATE "C"' } as Record<string, string>)[token.toUpperCase()] ?? token);
  return [ddl.trim().replace(/;?$/, ";"), ...tables.map((table) => `ALTER TABLE ${table} ADD COLUMN IF NOT EXISTS _rowid BIGINT GENERATED BY DEFAULT AS IDENTITY;`)].join("\n");
}

/** Applies pending migrations; concurrent instances wait on the advisory lock and then find nothing to do. */
export async function migratePostgres(pool: postgres.Sql) {
  const applied = async (q: postgres.Sql | postgres.TransactionSql) =>
    (await q`SELECT to_regclass('schema_migrations') IS NOT NULL AS ok`)[0].ok
      ? new Set((await q`SELECT name FROM schema_migrations`).map((row) => row.name as string))
      : new Set<string>();
  const migrations = portableMigrations();
  const done = await applied(pool);
  if (migrations.every((m) => done.has(m.name))) return [];
  return await pool.begin(async (tx) => {
    await tx`SELECT pg_advisory_xact_lock(hashtext(current_schema() || '.kedu_migrations')::bigint)`;
    await tx`CREATE TABLE IF NOT EXISTS schema_migrations(name TEXT PRIMARY KEY, applied TEXT NOT NULL)`;
    const current = await applied(tx);
    const names: string[] = [];
    for (const m of migrations.filter((m) => !current.has(m.name))) {
      await tx.unsafe(postgresDdl(m.sql));
      await tx`INSERT INTO schema_migrations VALUES(${m.name}, ${new Date().toISOString()})`;
      names.push(m.name);
    }
    return names;
  }) as string[];
}
