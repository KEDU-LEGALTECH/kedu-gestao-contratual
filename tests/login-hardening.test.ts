import { test, after } from "node:test";
import assert from "node:assert/strict";
import { mkdtempSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
process.env.DATABASE_PATH = join(mkdtempSync(join(tmpdir(), "kedu-login-hardening-")), "test.sqlite");
process.env.NODE_ENV = "test";
process.env.DEMO_SEED = "false";
process.env.GLPI_MODE = "demo";
process.env.GLPI_SYNC_TIMES = "";
const { default: app } = await import("../server/index.js");
const { sql, hash, verify, sessionKey } = await import("../server/db.js");
const { postgresDdl, portableMigrations } = await import("../server/migrations.js");

const server = app.listen(0, "127.0.0.1");
await new Promise(resolve => server.on("listening", resolve));
after(() => server.close());
const base = `http://127.0.0.1:${(server.address() as any).port}/api`;
// express-rate-limit also allows 20 sign-ins per address in 15 minutes: this file stays below that.
async function login(email: string, password: string) {
  const response = await fetch(base + "/login", { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify({ email, password }) });
  return { status: response.status, cookie: (response.headers.get("set-cookie") || "").split(";")[0] };
}
const call = (cookie: string, path: string, method: string, body?: unknown) =>
  fetch(base + path, { method, headers: { cookie, ...(body ? { "Content-Type": "application/json" } : {}) }, body: body ? JSON.stringify(body) : undefined });

await sql.run("INSERT INTO users VALUES(?,?,?,?,?)", "admin", "Administradora", "admin@empresa.test", "Administrador", hash("senha-da-admin-123"));
await sql.run("INSERT INTO users VALUES(?,?,?,?,?)", "alvo", "Alvo", "alvo@empresa.test", "Consulta", hash("senha-do-alvo-123"));
await sql.run("INSERT INTO users VALUES(?,?,?,?,?)", "carla", "Carla", "carla@empresa.test", "Consulta", hash("senha-da-carla-123"));

test("dez senhas erradas bloqueiam o e-mail por 15 minutos, mesmo com a senha certa", async () => {
  for (let i = 0; i < 10; i++) assert.equal((await login("ALVO@empresa.test", "errada-" + i)).status, 401);
  assert.equal((await login("alvo@empresa.test", "senha-do-alvo-123")).status, 429);
  const { n } = await sql.one("SELECT COUNT(*) AS n FROM login_attempts WHERE subject='email:alvo@empresa.test'");
  assert.equal(n, 10, "as tentativas ficam no banco, compartilhadas entre instâncias");
});

test("entrada correta zera as tentativas do e-mail", async () => {
  for (let i = 0; i < 3; i++) assert.equal((await login("carla@empresa.test", "errada")).status, 401);
  assert.equal((await login("carla@empresa.test", "senha-da-carla-123")).status, 200);
  assert.equal((await sql.one("SELECT COUNT(*) AS n FROM login_attempts WHERE subject='email:carla@empresa.test'")).n, 0);
});

test("sessão gravada pelo hash do token e e-mail sem duplicar por maiúsculas", async () => {
  const admin = await login("admin@empresa.test", "senha-da-admin-123");
  const token = admin.cookie.split("=")[1];
  assert.equal(await sql.one("SELECT token FROM sessions WHERE token=?", token), undefined, "o token não fica no banco");
  assert.ok(await sql.one("SELECT token FROM sessions WHERE token=?", sessionKey(token)));
  const user = { name: "Bia Souza", role: "Consulta", password: "senha-da-bia-1234" };
  assert.equal((await call(admin.cookie, "/users", "POST", { ...user, email: "Bia@Empresa.test" })).status, 200);
  assert.equal((await sql.one("SELECT email FROM users WHERE lower(email)='bia@empresa.test'")).email, "bia@empresa.test");
  const duplicate = await call(admin.cookie, "/users", "POST", { ...user, email: "bia@empresa.test" });
  assert.equal(duplicate.status, 400);
  assert.match((await duplicate.json()).error, /Já existe um usuário com este e-mail/);
  assert.equal((await call(admin.cookie, "/logout", "POST")).status, 200);
  assert.equal(await sql.one("SELECT token FROM sessions WHERE token=?", sessionKey(token)), undefined);
});

test("senha gravada em formato inválido é recusada sem erro do servidor", () => {
  assert.equal(verify("qualquer", ""), false);
  assert.equal(verify("qualquer", "sem-separador"), false);
  assert.equal(verify("qualquer", "sal:abc"), false);
  assert.equal(verify("senha-certa-123", hash("senha-certa-123")), true);
});

test("migrações a partir da 020 rodam no SQLite e são convertidas para o PostgreSQL", () => {
  const names = portableMigrations().map(m => m.name);
  assert.deepEqual(names.slice(0, 3), ["020.sql", "021.sql", "022.sql"]);
  const ddl = postgresDdl(portableMigrations().find(m => m.name === "022.sql")!.sql);
  assert.match(ddl, /subject TEXT COLLATE "C" NOT NULL/);
  assert.match(ddl, /created BIGINT NOT NULL/);
  assert.match(ddl, /ALTER TABLE login_attempts ADD COLUMN IF NOT EXISTS _rowid BIGINT GENERATED BY DEFAULT AS IDENTITY;/);
  assert.doesNotMatch(ddl, /--/);
  for (const m of portableMigrations())
    for (const statement of m.sql.replace(/--[^\n]*/g, "").split(";").map(s => s.trim()).filter(Boolean))
      assert.match(statement, /^CREATE (TABLE|INDEX|UNIQUE INDEX) IF NOT EXISTS\b/i, `${m.name} precisa ser repetível: ${statement.slice(0, 60)}`);
});
