import { test } from "node:test";
import assert from "node:assert/strict";
import { mkdtempSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { spawnSync } from "node:child_process";
process.env.DATABASE_PATH = join(mkdtempSync(join(tmpdir(), "kedu-cleanup-")), "test.sqlite");
process.env.NODE_ENV = "test";
process.env.DEMO_SEED = "true";
process.env.GLPI_MODE = "demo";
const { seed } = await import("../server/seed.js");
const { seedCatalog } = await import("../server/governance-routes.js");
const { registerOfficialCatalog } = await import("../server/official-templates.js");
const { one, all, run, sql } = await import("../server/db.js");
const { cleanupDemoData } = await import("../server/cleanup-demo.js");
await seedCatalog();
await registerOfficialCatalog();
await sql.run("INSERT INTO schools VALUES('real-school','Escola real','Escola real Ltda','11.444.777/0001-61','Endereço real','Contato real')");
await sql.run("INSERT INTO contracts(id,school_id,status) VALUES('real-contract','real-school','Assinado')");
await sql.run("INSERT INTO demands(id,school_id,contract_id,type,stage,priority,owner,due,data,created) VALUES('REAL-1','real-school','real-contract','Contrato de garantia','Recebido','Normal','u2','2030-01-01','{}','2026-10-20')");
await sql.run("INSERT INTO glpi_tickets VALUES('real-ticket','real','Título real','2','real-hash','{}','{}','vinculado','REAL-1','2026-10-20','2026-10-20',NULL)");
await sql.run("INSERT INTO glpi_ticket_versions VALUES('real-version','real-ticket','real-hash','{}','2026-10-20')");
await sql.run("INSERT INTO school_glpi_origins VALUES('real-school','real-ticket','2026-10-20',NULL,NULL)");
await sql.run("INSERT INTO signed_history VALUES('real-history','real-contract',0,'Clint','Referência real','2026-01-01','u0','2026-10-20')");
await sql.run("INSERT INTO signed_history VALUES('seed-history','c4',0,'Clint','Referência fictícia','2026-01-01','u0','2026-10-20')");
await sql.run("INSERT INTO history_confirmations VALUES('seed-confirmation','c4',0,'Clint','Referência fictícia','2026-01-01','u0','2026-10-20')");
await sql.run("INSERT INTO demand_baselines VALUES('seed-baseline','KD-0001','Vigência','{}','Referência fictícia','u0','2026-10-20')");
await sql.run("INSERT INTO sessions VALUES('keep-admin-session','u0',?)", Date.now() + 60000);
const realSchool = await sql.one("SELECT * FROM schools WHERE id='real-school'");
const realDemand = await sql.one("SELECT * FROM demands WHERE id='REAL-1'");
const realTicket = await sql.one("SELECT * FROM glpi_tickets WHERE external_id='real-ticket'");
const officialIds = await sql.all("SELECT version_id FROM template_sources ORDER BY version_id");

test("Limpeza exige demonstração desativada", async () => {
  await assert.rejects(async () => cleanupDemoData(), /Desative DEMO_SEED/);
  assert.equal((await sql.one("SELECT COUNT(*) n FROM schools")).n, 9);
  process.env.DEMO_SEED = "false";
});
test("Cadastro da carga alterado impede exclusão e mantém a integridade", async () => {
  await sql.run("UPDATE schools SET address='Endereço agora real' WHERE id='s0'");
  await assert.rejects(async () => cleanupDemoData(), /foi alterado/);
  assert.equal((await sql.one("SELECT COUNT(*) n FROM schools")).n, 9);
  await sql.run("UPDATE schools SET address='Fortaleza, CE • Dados fictícios' WHERE id='s0'");
});
test("Dependência real em contrato fictício impede toda a limpeza", async () => {
  await sql.run("UPDATE demands SET data=? WHERE id='REAL-1'", JSON.stringify({ matriz: "c0" }));
  await assert.rejects(async () => cleanupDemoData(), /Demanda externa depende/);
  assert.equal((await sql.one("SELECT COUNT(*) n FROM demands")).n, 9);
  assert.ok(await sql.one("SELECT name FROM sqlite_master WHERE name='no_delete_signed_history'"));
  await sql.run("UPDATE demands SET data='{}' WHERE id='REAL-1'");
});
test("Remove carga fictícia e preserva dados reais, oficiais, acesso e gatilhos", async () => {
  const result = await cleanupDemoData();
  assert.equal(result.schoolsRemoved, 8);
  assert.equal(result.demandsRemoved, 8);
  assert.equal(result.contractsRemoved, 8);
  assert.ok(result.templateVersionsRemoved >= 6);
  assert.deepEqual(await sql.one("SELECT * FROM schools"), realSchool);
  assert.deepEqual(await sql.one("SELECT * FROM demands"), realDemand);
  assert.deepEqual(await sql.one("SELECT * FROM glpi_tickets"), realTicket);
  assert.deepEqual(await sql.all("SELECT version_id FROM template_sources ORDER BY version_id"), officialIds);
  assert.ok(await sql.one("SELECT * FROM sessions WHERE token='keep-admin-session'"));
  assert.equal((await sql.one("SELECT name FROM users WHERE id='u0'")).name, "Conta local — Administrador");
  assert.equal((await sql.one("SELECT name FROM users WHERE id='u2'")).name, "Conta local — Operação");
  assert.equal((await sql.one("SELECT COUNT(*) n FROM template_catalog WHERE demonstration=1")).n, 0);
  assert.equal((await sql.one("SELECT COUNT(*) n FROM evidence_files")).n, 0);
  assert.equal((await sql.one("SELECT COUNT(*) n FROM documents")).n, 0);
  await assert.rejects(async () => sql.run("DELETE FROM signed_history WHERE id='real-history'"), /imutável/);
  await assert.rejects(async () => sql.run("DELETE FROM glpi_ticket_versions WHERE id='real-version'"), /imutável/);
  assert.deepEqual(await sql.all("PRAGMA foreign_key_check"), []);
  assert.equal((await cleanupDemoData()).schoolsRemoved, 0);
});
test("Reiniciar com DEMO_SEED=true não recria exemplos no banco limpo", () => {
  const child = spawnSync(process.execPath, ["--import", "tsx", "--input-type=module", "-e", 'await import("./server/seed.ts");const {seedCatalog}=await import("./server/governance-routes.ts");seedCatalog();const {one}=await import("./server/db.ts");console.log(JSON.stringify({schools:one("SELECT COUNT(*) n FROM schools").n,demands:one("SELECT COUNT(*) n FROM demands").n,demo:one("SELECT COUNT(*) n FROM template_catalog WHERE demonstration=1").n}));'], { encoding: "utf8", env: { ...process.env, DEMO_SEED: "true" } });
  assert.equal(child.status, 0, child.stderr);
  assert.deepEqual(JSON.parse(child.stdout.trim()), { schools: 1, demands: 1, demo: 0 });
});
